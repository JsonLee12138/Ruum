    #[test]
    fn config_atomic_save_and_load() {
        let temp = tempfile::tempdir().unwrap();
        let path = temp.path().join("nested/watchdog.json");

        // Absent file returns default
        let loaded = load_config(&path).unwrap();
        assert_eq!(loaded, WatchdogConfig::default());

        // Modify and save
        let custom = WatchdogConfig {
            enabled: true,
            min_free_gb: 42,
            ai_provider: AiCliProvider::Pi,
            custom_command: "my-pi".to_string(),
            ..WatchdogConfig::default()
        };
        save_config(&path, &custom).unwrap();

        let reloaded = load_config(&path).unwrap();
        assert_eq!(reloaded, custom);

        // Corrupt file fails with InvalidData
        fs::write(&path, "not-valid-json").unwrap();
        assert_eq!(
            load_config(&path).unwrap_err().kind(),
            io::ErrorKind::InvalidData
        );
    }


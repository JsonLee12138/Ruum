test("5. Cargo.lock external dependency change triggers rust and macOS bundle", () => {
  const extChanged = SAMPLE_CARGO_LOCK.replace(
    'version = "1.0.95"',
    'version = "1.0.96"',
  );
  const crates = new Set(["ruum-app", "ruum-core", "xtask"]);

  const lockVersionOnly = isCargoLockWorkspaceVersionOnly(
    SAMPLE_CARGO_LOCK,
    extChanged,
    crates,
  );
  assert.equal(lockVersionOnly, false);

  // parseWorkspaceCrateNames fails open to an empty Set if any member read fails.
  const failedReadSet = parseWorkspaceCrateNames(
    SAMPLE_ROOT_CARGO_TOML,
    () => null,
  );
  assert.equal(failedReadSet.size, 0);
  assert.equal(
    isCargoLockWorkspaceVersionOnly(
      SAMPLE_CARGO_LOCK,
      SAMPLE_CARGO_LOCK.replaceAll('version = "0.2.3-beta.1"', 'version = "0.2.4"'),
      failedReadSet,
    ),
    false,
  );

  const result = classifyChanges({
    eventName: "push",
    changedFiles: ["Cargo.lock"],
    includeMacosIntel: false,
    cargoTomlVersionOnly: false,
    cargoLockWorkspaceVersionOnly: lockVersionOnly,
    fallback: false,
  });
  assert.equal(result.run_rust, true);
  assert.equal(result.run_macos_bundle, true);
  assert.equal(result.run_windows_release_check, true);
});


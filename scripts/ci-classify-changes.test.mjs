test("1. pure Cargo.toml [workspace.package] version bump skips rust and bundle", () => {
  const bumped = SAMPLE_ROOT_CARGO_TOML.replace(
    'version = "0.2.3-beta.1"',
    'version = "0.2.4" # release bump',
  );
  const cargoTomlVersionOnly = isCargoTomlVersionOnly(
    SAMPLE_ROOT_CARGO_TOML,
    bumped,
  );
  assert.equal(cargoTomlVersionOnly, true);

  const crlfOld = SAMPLE_ROOT_CARGO_TOML.replaceAll("\n", "\r\n");
  const crlfNew = bumped.replaceAll("\n", "\r\n");
  assert.equal(isCargoTomlVersionOnly(crlfOld, crlfNew), true);

  const result = classifyChanges({
    eventName: "push",
    changedFiles: ["Cargo.toml"],
    includeMacosIntel: false,
    cargoTomlVersionOnly,
    cargoLockWorkspaceVersionOnly: false,
    fallback: false,
  });

  assert.deepEqual(
    {
      run_rust: result.run_rust,
      run_macos_bundle: result.run_macos_bundle,
      run_worker: result.run_worker,
      run_ci_scripts: result.run_ci_scripts,
      run_macos_intel: result.run_macos_intel,
      run_windows_release_check: result.run_windows_release_check,
    },
    {
      run_rust: false,
      run_macos_bundle: false,
      run_worker: false,
      run_ci_scripts: false,
      run_macos_intel: false,
      run_windows_release_check: false,
    },
  );
});

test("2. release bump (Cargo.toml + Cargo.lock workspace versions + CHANGELOG.md) skips heavy builds", () => {
  const bumpedToml = SAMPLE_ROOT_CARGO_TOML.replace(
    'version = "0.2.3-beta.1"',
    'version = "0.2.3"',
  );
  const bumpedLock = SAMPLE_CARGO_LOCK.replaceAll(
    'version = "0.2.3-beta.1"',
    'version = "0.2.3"',
  );

  const memberManifests = {
    "crates/ruum-app/Cargo.toml": '[package]\nname = "ruum-app"\n',
    "crates/ruum-core/Cargo.toml": '[package]\nname = "ruum-core"\n',
    "xtask/Cargo.toml": '[package]\nname = "xtask"\n',
  };
  const crateNames = parseWorkspaceCrateNames(
    bumpedToml,
    (memberPath) => memberManifests[memberPath],
  );
  assert.deepEqual(
    [...crateNames].sort(),
    ["ruum-app", "ruum-core", "xtask"],
  );

  const cargoTomlVersionOnly = isCargoTomlVersionOnly(
    SAMPLE_ROOT_CARGO_TOML,
    bumpedToml,
  );
  const cargoLockWorkspaceVersionOnly = isCargoLockWorkspaceVersionOnly(
    SAMPLE_CARGO_LOCK,
    bumpedLock,
    crateNames,
  );
  assert.equal(cargoTomlVersionOnly, true);
  assert.equal(cargoLockWorkspaceVersionOnly, true);

  assert.equal(isDocOrMetadataPath("CHANGELOG.md"), true);
  assert.equal(isDocOrMetadataPath("./docs/architecture.png"), true);
  assert.equal(isDocOrMetadataPath(".agents\\rules\\ci-and-release.md"), true);
  assert.equal(isDocOrMetadataPath(".artifacts/PLAN.md"), true);
  assert.equal(isDocOrMetadataPath("cliff.toml"), true);
  assert.equal(isDocOrMetadataPath("LICENSE"), true);
  assert.equal(isDocOrMetadataPath(".gitignore"), true);
  assert.equal(isDocOrMetadataPath(".editorconfig"), true);
  assert.equal(isDocOrMetadataPath("crates/ruum-core/src/lib.rs"), false);

  const result = classifyChanges({
    eventName: "pull_request",
    changedFiles: ["Cargo.toml", "Cargo.lock", "CHANGELOG.md"],
    includeMacosIntel: false,
    cargoTomlVersionOnly,
    cargoLockWorkspaceVersionOnly,
    fallback: false,
  });

  assert.deepEqual(
    {
      run_rust: result.run_rust,
      run_macos_bundle: result.run_macos_bundle,
      run_worker: result.run_worker,
      run_ci_scripts: result.run_ci_scripts,
      run_windows_release_check: result.run_windows_release_check,
    },
    {
      run_rust: false,
      run_macos_bundle: false,
      run_worker: false,
      run_ci_scripts: false,
      run_windows_release_check: false,
    },
  );
});

test("3. Cargo.toml dependency change alone or alongside version bump triggers rust and macOS bundle", () => {
  const depOnly = SAMPLE_ROOT_CARGO_TOML.replace(
    'anyhow = "1"',
    'anyhow = "1.0.95"',
  );
  const depAndVer = depOnly.replace(
    'version = "0.2.3-beta.1"',
    'version = "0.2.4"',
  );

  assert.equal(isCargoTomlVersionOnly(SAMPLE_ROOT_CARGO_TOML, depOnly), false);
  assert.equal(
    isCargoTomlVersionOnly(SAMPLE_ROOT_CARGO_TOML, depAndVer),
    false,
  );
  assert.equal(
    isCargoTomlVersionOnly(
      SAMPLE_ROOT_CARGO_TOML,
      `${SAMPLE_ROOT_CARGO_TOML}serde = "1"\n`,
    ),
    false,
  );

  for (const flag of [
    isCargoTomlVersionOnly(SAMPLE_ROOT_CARGO_TOML, depOnly),
    isCargoTomlVersionOnly(SAMPLE_ROOT_CARGO_TOML, depAndVer),
  ]) {
    const result = classifyChanges({
      eventName: "push",
      changedFiles: ["Cargo.toml"],
      includeMacosIntel: false,
      cargoTomlVersionOnly: flag,
      cargoLockWorkspaceVersionOnly: false,
      fallback: false,
    });
    assert.equal(result.run_rust, true);
    assert.equal(result.run_macos_bundle, true);
    assert.equal(result.run_windows_release_check, true);
  }
});

